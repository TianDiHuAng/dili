def fmt(name):
    d=W[name];v=d["value"];c=d["code"]
    if c=="SP.POP.TOTL": s=f"{int(v):,} 人"
    elif c=="SP.DYN.LE00.IN": s=f"{v:.1f} 岁"
    elif c=="NY.GDP.PCAP.CD" or c=="NY.GNP.PCAP.CD": s=f"{v:,.0f} 美元"
    elif c=="EN.GHG.CO2.MT.CE.AR5": s=f"{v:,.2f} Mt CO₂e"
    elif c=="ER.FSH.PROD.MT": s=f"{v:,.0f} 吨"
    elif c=="AG.YLD.CREL.KG": s=f"{v:,.1f} 千克/公顷"
    elif c=="AG.CON.FERT.ZS": s=f"{v:.1f} 千克/公顷"
    elif c=="SH.DYN.MORT": s=f"{v:.1f}‰"
    elif c=="SP.POP.GROW": s=f"{v:.2f}%"
    else: s=f"{v:.1f}%"
    return s,c

