def build_matrix(unit_docs):
    out = {}
    for uid, doc in unit_docs.items():
        out[uid] = {}
        for e in doc["entries"]:
            out[uid].setdefault(e["theme"], 0)
            out[uid][e["theme"]] += 1
    return out

