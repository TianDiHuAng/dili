def slug(s):
    """仅 a-z0-9-：ASCII 保留，非 ASCII 用 x+码点十六进制编码，保证唯一且可回读。"""
    out = []
    for ch in s.lower():
        if ch.isascii() and ch.isalnum():
            out.append(ch)
        else:
            out.append("x" + format(ord(ch), "x"))
    r = "".join(out)
    while "--" in r:
        r = r.replace("--", "-")
    return r.strip("-")


