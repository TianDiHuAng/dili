def add_new(docs):
    out=[]
    for uid,title,tier,region,theme,tp,overview,sources,rel_title in NEW:
        if any(e["title"]==title for e in docs[uid]["entries"]): continue
        rid=None
        for d in docs.values():
            for e in d["entries"]:
                if e["title"]==rel_title: rid=e["id"];break
            if rid:break
        e={"id":uid+"-"+sid(title),"title":title,"tier":tier,"unit_id":uid,"region":region,
           "theme":theme,"level":"L1","status":"L1完成(第3轮)",
           "definition":title+"："+overview,"time_or_place":tp,"overview":overview,
           "related":[rid] if rid else [],"sources":sources,"needs_verification":True,
           "pending_notes":"B1/B6 缺口补入；专门资料与现状数值待按年份核验。",
           "outlines":["OpenStax Geography 教材目录","NOAA/NASA 近期动态","UN M49"],"last_update":TODAY}
        docs[uid]["entries"].append(e);out.append(e["id"])
    return out

